// Package fake is a stand-in slicer for development and tests without Bambu Studio. It
// writes a real .gcode.3mf (same layout as Bambu Studio) with estimates computed from
// the mesh volume and simple perimeter toolpaths, so the viewer and the printer path
// can be exercised end to end. Its numbers are rough; never use it for real prints.
package fake

import (
	"archive/zip"
	"context"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"

	"github.com/margarit/printpipe/internal/mesh"
	"github.com/margarit/printpipe/internal/slicer"
)

const Kind = "fake"

func init() {
	slicer.Register(slicer.Driver{Kind: Kind, Label: "Fake slicer (development only)", New: func(slicer.Deps) slicer.Slicer { return Slicer{} }})
}

type Slicer struct{}

func (Slicer) Kind() string { return Kind }

const plaDensity = 1.24 // g/cm³

func (Slicer) Slice(ctx context.Context, in slicer.Input) (slicer.Result, error) {
	m, err := mesh.ReadFile(in.Model)
	if err != nil {
		return slicer.Result{}, err
	}
	lh := in.Overrides.LayerHeight
	if lh == 0 {
		lh = 0.2
	}
	infill := 15
	if in.Overrides.Infill != nil {
		infill = *in.Overrides.Infill
	}
	supports := in.Overrides.Supports == nil || *in.Overrides.Supports
	size := m.Size()
	layers := int(math.Max(1, math.Ceil(size.Z/lh)))
	// Shell plus infill share of the volume, in grams.
	solid := math.Min(1, 0.35+0.65*float64(infill)/100)
	grams := math.Round(m.Volume()/1000*plaDensity*solid*100) / 100
	metres := math.Round(grams/plaDensity/(math.Pi*0.0875*0.0875)*100/100) / 100 // 1.75 mm filament
	seconds := int(180 + grams*90 + float64(layers)*2)

	if err := os.MkdirAll(filepath.Dir(in.OutPath), 0o755); err != nil {
		return slicer.Result{}, err
	}
	if err := write(in.OutPath, seconds, grams, metres, layers, lh, supports, size); err != nil {
		return slicer.Result{}, err
	}
	return slicer.Result{Path: in.OutPath, Seconds: seconds, Layers: layers, LayerHeight: lh,
		Filaments: []slicer.Filament{{Type: "PLA", Grams: grams, Metres: metres}}}, nil
}

func write(path string, seconds int, grams, metres float64, layers int, lh float64, supports bool, size mesh.Vec) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	zw := zip.NewWriter(f)
	add := func(name, body string) {
		w, _ := zw.Create(name)
		w.Write([]byte(body))
	}
	add("Metadata/slice_info.config", fmt.Sprintf(`<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="%d"/>
    <metadata key="weight" value="%.2f"/>
    <metadata key="outside" value="false"/>
    <metadata key="support_used" value="false"/>
    <filament id="1" type="PLA" color="#F2754E" used_m="%.2f" used_g="%.2f"/>
  </plate>
</config>
`, seconds, grams, metres, grams))
	add("Metadata/project_settings.config", fmt.Sprintf(`{"layer_height": "%g", "enable_support": "%v", "printer_model": "Fake slicer"}`, lh, map[bool]int{true: 1, false: 0}[supports]))
	add("Metadata/plate_1.gcode", gcode(layers, lh, seconds, grams, size))
	if err := zw.Close(); err != nil {
		return err
	}
	return f.Close()
}

// gcode draws one rectangular perimeter per layer around the part's footprint, centred on a 256 mm bed.
func gcode(layers int, lh float64, seconds int, grams float64, size mesh.Vec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "; HEADER_BLOCK_START\n; generated by printpipe fake slicer\n; model printing time: %dm; total estimated time: %dm\n; total layer number: %d\n; total filament weight [g] : %.2f\n; HEADER_BLOCK_END\n",
		seconds/60, seconds/60, layers, grams)
	b.WriteString("G90\nM83\nG28\n")
	x0, y0 := 128-size.X/2, 128-size.Y/2
	x1, y1 := x0+size.X, y0+size.Y
	for l := 1; l <= layers; l++ {
		z := float64(l) * lh
		fmt.Fprintf(&b, ";LAYER_CHANGE\n;Z:%.2f\nG0 X%.2f Y%.2f Z%.2f F9000\n", z, x0, y0, z)
		for _, p := range [][2]float64{{x1, y0}, {x1, y1}, {x0, y1}, {x0, y0}} {
			fmt.Fprintf(&b, "G1 X%.2f Y%.2f E0.5 F3000\n", p[0], p[1])
		}
	}
	b.WriteString("M400\n")
	return b.String()
}
